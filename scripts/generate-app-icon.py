"""Build matching WPF vector and multi-resolution Windows clock icons (requires Pillow)."""
from pathlib import Path
from PIL import Image, ImageDraw

# Analog clock with distinct hands, using the Slate palette.
background = '#202B3B'
ring = '#BECFE5'
hands = '#EDF2FA'
endpoints = [(94, 108), (166, 90)]
scale = 4
image = Image.new('RGBA', (256 * scale, 256 * scale))
draw = ImageDraw.Draw(image)
def box(values):
    return tuple(value * scale for value in values)
draw.rounded_rectangle(box((4, 4, 252, 252)), radius=48 * scale, fill=background)
draw.ellipse(box((42, 42, 214, 214)), outline=ring, width=12 * scale)
# Rounded hands stay recognizable at tray-icon sizes.
for endpoint in endpoints:
    draw.line(box((128, 128, *endpoint)), fill=hands, width=14 * scale)
    x, y = endpoint
    draw.ellipse(box((x - 7, y - 7, x + 7, y + 7)), fill=hands)
draw.ellipse(box((119, 119, 137, 137)), fill=hands)
image = image.resize((256, 256), Image.Resampling.LANCZOS)
output = Path(__file__).resolve().parents[1] / 'desktop/TimeTracker.Windows/Assets/app.ico'
image.save(output, sizes=[(size, size) for size in (16, 20, 24, 32, 40, 48, 64, 128, 256)])

# WPF renders this geometry at the display DPI instead of enlarging an ICO frame.
hand_path = " ".join(f"M 128,128 L {x},{y}" for x, y in endpoints)
output.with_name('Clock.xaml').write_text(f'''<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"
 xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">
 <!-- Generated by scripts/generate-app-icon.py; matches app.ico. -->
 <DrawingImage x:Key="AppClock">
  <DrawingImage.Drawing><DrawingGroup>
   <GeometryDrawing Brush="Transparent"><GeometryDrawing.Geometry><RectangleGeometry Rect="0,0,256,256"/></GeometryDrawing.Geometry></GeometryDrawing>
   <GeometryDrawing Brush="{background}"><GeometryDrawing.Geometry><RectangleGeometry Rect="4,4,248,248" RadiusX="48" RadiusY="48"/></GeometryDrawing.Geometry></GeometryDrawing>
   <GeometryDrawing><GeometryDrawing.Pen><Pen Brush="{ring}" Thickness="12"/></GeometryDrawing.Pen><GeometryDrawing.Geometry><EllipseGeometry Center="128,128" RadiusX="80" RadiusY="80"/></GeometryDrawing.Geometry></GeometryDrawing>
   <GeometryDrawing Geometry="{hand_path}"><GeometryDrawing.Pen><Pen Brush="{hands}" Thickness="14" StartLineCap="Round" EndLineCap="Round"/></GeometryDrawing.Pen></GeometryDrawing>
   <GeometryDrawing Brush="{hands}"><GeometryDrawing.Geometry><EllipseGeometry Center="128,128" RadiusX="9" RadiusY="9"/></GeometryDrawing.Geometry></GeometryDrawing>
  </DrawingGroup></DrawingImage.Drawing>
 </DrawingImage>
</ResourceDictionary>
''', encoding='utf-8')
